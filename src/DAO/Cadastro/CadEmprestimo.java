    private void btn_AdicionarGameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_AdicionarGameActionPerformed

        Games gameSelecionado = (Games) cbm_Jogo.getSelectedItem();

        if (gameSelecionado != null) {

            ItemEmprestimo item = new ItemEmprestimo(gameSelecionado.getId(), gameSelecionado.getNome());
            listaItens.add(item);

            atualizarTabelaItens();

            cbm_Jogo.removeItem(gameSelecionado);
           
        }
    }

    private void atualizarTabelaItens() {
        DefaultTableModel model = new DefaultTableModel(new Object[]{"ID Jogo", "Nome do Jogo"}, 0);
        for (ItemEmprestimo item : listaItens) {
            model.addRow(new Object[]{item.getIdGame(), item.getNomeGame()});
        }
        tbl_Itens.setModel(model);

    }//GEN-LAST:event_btn_AdicionarGameActionPerformed

