    private void btn_PesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_PesquisarActionPerformed

        String idTexto = txt_IdAmigo.getText().trim();

        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, digite o ID para pesquisar!");
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);
            DAO.ArquivosDao.AmigoDAO dao = new DAO.ArquivosDao.AmigoDAO();
            DAO.Entidades.Amigo amigo = dao.buscarPorId(id);

            if (amigo != null) {
                // Preenche os campos da tela com os dados retornados do banco
                txt_Nome.setText(amigo.getNome());
                txt_Telefone.setText(amigo.getTelefone());
                txt_Email.setText(amigo.getEmail());
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Amigo não encontrado!");
                // Limpa os campos caso não encontre
                txt_Nome.setText("");
                txt_Telefone.setText("");
                txt_Email.setText("");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "O ID deve ser um número válido!");
        }

    }//GEN-LAST:event_btn_PesquisarActionPerformed

    private void btn_ExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ExcluirActionPerformed

        String idTexto = txt_IdAmigo.getText().trim();

        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pesquise um amigo pelo ID antes de excluir!");
            return;
        }
        
        int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir este amigo?",
                "Atenção",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(idTexto);
                DAO.ArquivosDao.AmigoDAO dao = new DAO.ArquivosDao.AmigoDAO();

                if (dao.excluir(id)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Amigo excluído com sucesso!");
                    txt_IdAmigo.setText("");
                    txt_Nome.setText("");
                    txt_Telefone.setText("");
                    txt_Email.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir amigo!");
                }
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "ID inválido!");
            }
        }

    }//GEN-LAST:event_btn_ExcluirActionPerformed

