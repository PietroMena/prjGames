    private void btn_SalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_SalvarActionPerformed

        int id = Integer.parseInt(txt_IdAmigo.getText());
        String nome = txt_Nome.getText().trim();
        String telefone = txt_Telefone.getText().trim();
        String email = txt_Email.getText().trim();

        if (nome.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "O nome não pode estar vazio!");
            return;
        }

        DAO.Entidades.Amigo amigo = new DAO.Entidades.Amigo(id, nome, telefone, email);
        DAO.ArquivosDao.AmigoDAO dao = new DAO.ArquivosDao.AmigoDAO();

        if (dao.editar(amigo)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Amigo atualizado com sucesso!");
            this.dispose(); // Fecha a tela de edição
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar amigo!");
        }

    }//GEN-LAST:event_btn_SalvarActionPerformed

