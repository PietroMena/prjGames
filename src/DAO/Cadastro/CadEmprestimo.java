    private void limparFormulario() {

        if (cmb_Amigo.getItemCount() > 0) {
            cmb_Amigo.setSelectedIndex(0);
        }

        listaItens.clear();
        DefaultTableModel model = (DefaultTableModel) tbl_Itens.getModel();
        model.setRowCount(0);
        carregarGames();
    }

    // No topo da classe CadEmprestimo, declare a lista temporária:
