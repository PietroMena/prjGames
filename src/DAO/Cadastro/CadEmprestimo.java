    private void carregarAmigos() {
        AmigoDAO dao = new AmigoDAO();
        List<Amigo> lista = dao.getAmigos();
        cmb_Amigo.removeAllItems();
        if (lista != null) {
            for (Amigo a : lista) {
                cmb_Amigo.addItem(a);
            }
        }
    }

    private void carregarGames() {
        GamesDAO dao = new GamesDAO();

        List<Games> lista = dao.getGamesDisponiveis();
        cbm_Jogo.removeAllItems();
        if (lista != null) {
            for (Games g : lista) {
                cbm_Jogo.addItem(g);
            }
        }
    }

