    private void btn_SalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_SalvarActionPerformed

        Amigo amigoSelecionado = (Amigo) cmb_Amigo.getSelectedItem();

        if (amigoSelecionado == null || listaItens.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecione um amigo e adicione pelo menos um jogo!");
            return;
        }

        Emprestimo emp = new Emprestimo();
        emp.setIdAmigo(amigoSelecionado.getId());
        emp.setDataEmprestimo(new java.sql.Date(System.currentTimeMillis()));

        EmprestimoDAO empDAO = new EmprestimoDAO();
        int idEmprestimoGerado = empDAO.inserir(emp);

        if (idEmprestimoGerado > 0) {

            ItemEmprestimoDAO itemDAO = new ItemEmprestimoDAO();
            boolean sucesso = itemDAO.salvarItens(idEmprestimoGerado, listaItens);

            if (sucesso) {
                JOptionPane.showMessageDialog(this, "Empréstimo realizado com sucesso!");
                listaItens.clear();
                atualizarTabelaItens();
                carregarGames();
            }
        }

    }//GEN-LAST:event_btn_SalvarActionPerformed

