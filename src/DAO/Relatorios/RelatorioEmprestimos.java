    private void btn_DevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_DevolverActionPerformed
        int linhaSelecionada = tbl_Emprestimos.getSelectedRow();

        if (linhaSelecionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um empréstimo na tabela para devolver");
            return;
        }

        int idEmprestimo = (int) tbl_Emprestimos.getValueAt(linhaSelecionada, 0);

        EmprestimoDAO dao = new EmprestimoDAO();
        if (dao.devolver(idEmprestimo)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Devolução finalizado com sucesso");
            preencherTabela();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao registrar devolução");
        }
    }//GEN-LAST:event_btn_DevolverActionPerformed

