    private void btn_SalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_SalvarActionPerformed

        String nome = txt_Nome.getText().trim();
        String telefone = txt_Telefone.getText().trim();
        String email = txt_Email.getText().trim();

        // Validação simples
        if (nome.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha o nome!");
            return;
        }

        // Instanciar o modelo e preencher os dados
        DAO.Entidades.Amigo amigo = new DAO.Entidades.Amigo();
        amigo.setNome(nome);
        amigo.setTelefone(telefone);
        amigo.setEmail(email);

        // Instanciar o DAO e salvar na base de dados
        DAO.ArquivosDao.AmigoDAO dao = new DAO.ArquivosDao.AmigoDAO();
        if (dao.inserir(amigo)){ //Busca o método Inserir
            javax.swing.JOptionPane.showMessageDialog(this, "Amigo cadastrado com sucesso!");
            // Limpar campos após salvar
            txt_Nome.setText("");
            txt_Telefone.setText("");
            txt_Email.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao cadastrar amigo!");
        }

    }//GEN-LAST:event_btn_SalvarActionPerformed

