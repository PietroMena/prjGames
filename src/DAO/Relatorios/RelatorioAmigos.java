    public void preencherTabela() {
        AmigoDAO aDAO = new AmigoDAO();
        List<Amigo> listaAmigos = aDAO.getAmigos();

        DefaultTableModel tabelaAmigos = (DefaultTableModel) tbl_Amigos.getModel();

        for (Amigo a: listaAmigos) {
            Object[] obj = new Object[]{
                a.getId(),
                a.getNome(),
                a.getTelefone(),
                a.getEmail()    
               
            };
            tabelaAmigos.addRow(obj);
        }
    }


